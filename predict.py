def load_days() -> dict:
    days = {}
    if not ARCHIVE.exists():
        return days
    for path in sorted(ARCHIVE.glob("*.json")):
        if path.stem in ("latest", "index", "ledger"):
            continue
        try:
            day = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(day, dict) and day.get("date"):
            days[day["date"]] = day
    return days


def _write(path: Path, payload) -> None:
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    try:
        shown = path.relative_to(ROOT)
    except ValueError:  # writing outside the repo (tests, backfills)
        shown = path
    print(f"wrote {shown}")


def update_readme(snapshot: dict, ledger: dict) -> None:
    if not README.exists():
        return
    totals = ledger["totals"]
    baselines = ledger.get("baselines") or {}
    coin = baselines.get("coin_flip") or {}

    def num(value, places=3):
        return "—" if value is None else f"{value:.{places}f}"

    lines = [
        "<!-- LEDGER:START -->",
        f"### Standing — {snapshot['date']}",
        "",
    ]
    if totals["graded"]:
        lines += [
            f"**{totals['correct']} right / {totals['graded']} settled "
            f"({totals['accuracy']:.0%})** · Brier {num(totals['brier'])} "
            f"· log loss {num(totals['log_loss'])} · {totals['open']} still open",
            "",
            f"Saying \"50%\" to all {totals['graded']} of them instead would score "
            f"Brier {num(coin.get('brier'))}, log loss {num(coin.get('log_loss'))}. "
            "Lower is better; every figure below is only worth what it beats.",
            "",
            "| Call | Answered by | Settled | Right | Brier | Log loss |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        # The model variants sit out until they have 25 settled examples in
        # their family. Printing a dozen empty rows until then buries the six
        # that actually have a record, so they appear only once they do.
        for row in ledger["by_predictor"].values():
            if row["variant"] == "model" and not row["graded"]:
                continue
            right = (
                f"{row['correct']}/{row['graded']} ({row['accuracy']:.0%})"
                if row["graded"]
                else "—"
            )
            lines.append(
                f"| {row['question']} | {row['rule']} | n={row['graded']} | {right} "
                f"| {num(row['brier'])} | {num(row['log_loss'])} |"
            )
        lines.append(
            f"| _coin flip — the baseline_ | _50% to everything_ | n={totals['graded']} "
            f"| _50%_ | _{num(coin.get('brier'))}_ | _{num(coin.get('log_loss'))}_ |"
        )
        lines.append("")
        lines.append(
            f"_Sample is {totals['graded']} settled bets across {totals['days']} "
            "days. Nothing here is significant yet, and it is published daily "
            "precisely so that it becomes so._"
        )
        lines.append("")
    else:
        lines += ["_No bets have settled yet — the first ones resolve tomorrow._", ""]

    if snapshot.get("predictions"):
        lines += ["**Open bets, placed today:**", ""]
        for pred in snapshot["predictions"]:
            verdict = "**yes**" if pred["call"] else "**no**"
            lines.append(
                f"- {verdict} — {pred['question']} "
                f"_({pred['confidence']:.0%} confident, {pred['rule']})_"
            )
        lines.append("")
    lines.append("<!-- LEDGER:END -->")
    block = "\n".join(lines)

    text = README.read_text(encoding="utf-8")
    start, end = "<!-- LEDGER:START -->", "<!-- LEDGER:END -->"
    if start in text and end in text:
        text = text[: text.index(start)] + block + text[text.index(end) + len(end) :]
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    README.write_text(text, encoding="utf-8")
    print("wrote README.md")


def main() -> None:
    now = datetime.now(timezone.utc)
    today = now.strftime("%Y-%m-%d")
    ARCHIVE.mkdir(exist_ok=True)

    days = load_days()

    print("-- observe --")
    observations = collect_observations()

    # Today's observations are the truth that settles yesterday's bets, so
    # grading happens *before* predicting. That ordering is what makes the
    # models walk-forward: they train on this settled record, which by
    # construction contains nothing that resolves today or later.
    print("-- grade --")
    days[today] = {"date": today, "observations": observations, "predictions": []}
    grades = grade_all(days)

    print("-- predict --")
    predictions = make_predictions(observations, days, today, grades)

    snapshot = {
        "date": today,
        "fetched_at": now.isoformat(),
        "observations": observations,
        "predictions": predictions,
    }
    _write(ARCHIVE / f"{today}.json", snapshot)
    days[today] = snapshot

    # Recomputed over the finished archive; today's fresh bets cannot settle
    # yet, so this matches the grading above and stays a pure function of it.
    grades = grade_all(days)
    ledger = build_ledger(days, grades, today)
    totals = ledger["totals"]
    print(
        f"settled {totals['graded']} · correct {totals['correct']} "
        f"· open {totals['open']} · void {totals['void']}"
    )

    _write(ARCHIVE / "latest.json", snapshot)
    _write(ARCHIVE / "ledger.json", ledger)
    _write(ARCHIVE / "index.json", build_index(days, grades))
    update_readme(snapshot, ledger)
    print("done")


if __name__ == "__main__":
    main()
